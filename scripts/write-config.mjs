// Writes web/config.js from environment variables.
// Used by the Netlify build (see netlify.toml) so the committed config.js can stay on local
// Supabase values while the hosted site gets the hosted project.
//
//   SUPABASE_URL=https://xxxx.supabase.co SUPABASE_ANON_KEY=... node scripts/write-config.mjs

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const rawUrl = (process.env.SUPABASE_URL || '').trim();
const key = (process.env.SUPABASE_ANON_KEY || '').trim();

const missing = [];
if (!rawUrl) missing.push('SUPABASE_URL');
if (!key) missing.push('SUPABASE_ANON_KEY');
if (missing.length) {
  console.error(`Missing environment variable(s): ${missing.join(', ')}. Set them in Netlify -> Site configuration -> Environment variables.`);
  process.exit(1);
}

// supabase-js adds /rest/v1, /auth/v1 and /storage/v1 itself, so it needs the bare project
// address. Anything after the host (like a pasted /rest/v1/) breaks every call with
// "Invalid path specified in request URL", so keep only scheme + host.
const HINT = 'Use the Project URL from Supabase -> Project Settings -> API, like https://abcd1234.supabase.co';
let parsed;
try { parsed = new URL(rawUrl); } catch { parsed = null; }
if (!parsed || !['https:', 'http:'].includes(parsed.protocol)) {
  // Do not echo the value: a pasted postgresql:// connection string contains the database password
  console.error(`SUPABASE_URL is not a web address (it should start with https://). ${HINT}`);
  process.exit(1);
}
if (/(^|\.)supabase\.com$/.test(parsed.hostname)) {
  console.error(`SUPABASE_URL is a Supabase dashboard address, not the project API. ${HINT}`);
  process.exit(1);
}
const url = parsed.origin;
// Never echo the raw value: it may hold a user name and password (https://user:pass@host)
if (url !== rawUrl) console.warn(`Note: SUPABASE_URL trimmed to "${url}" (only the project address is used).`);
if (/[\s'"\\]/.test(key)) {
  console.error('SUPABASE_ANON_KEY contains spaces, quotes or backslashes.');
  process.exit(1);
}

// This file is public. The service_role key and sb_secret_ keys skip every database rule, so refuse
// anything that is not the public anon / publishable key.
const KEY_HINT = 'Use the anon public key (or the sb_publishable_ key) from Supabase -> Project Settings -> API.';
if (key.startsWith('sb_secret_')) {
  console.error(`SUPABASE_ANON_KEY is a secret key and would be published to everyone. ${KEY_HINT}`);
  process.exit(1);
}
if (/^eyJ[\w-]*\.eyJ[\w-]*\.[\w-]*$/.test(key)) {
  let role = null;
  try { role = JSON.parse(Buffer.from(key.split('.')[1], 'base64url').toString()).role; } catch { /* unreadable */ }
  if (role !== 'anon') {
    console.error(`SUPABASE_ANON_KEY is a ${role === 'service_role' ? 'service_role (secret)' : 'non-anon'} key and would be published to everyone. ${KEY_HINT}`);
    process.exit(1);
  }
}

// CONFIG_OUT lets tests write somewhere else; the build always writes web/config.js
const out = process.env.CONFIG_OUT || fileURLToPath(new URL('../web/config.js', import.meta.url));
writeFileSync(out, `// Generated by scripts/write-config.mjs during the hosted build. Do not edit here.
export const SUPABASE_URL = '${url}';
export const SUPABASE_ANON_KEY = '${key}';
`);
console.log(`Wrote web/config.js for ${url}`);
