// Writes web/config.js from environment variables.
// Used by the Netlify build (see netlify.toml) so the committed config.js can stay on local
// Supabase values while the hosted site gets the hosted project.
//
//   SUPABASE_URL=https://xxxx.supabase.co SUPABASE_ANON_KEY=... node scripts/write-config.mjs

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const url = (process.env.SUPABASE_URL || '').trim();
const key = (process.env.SUPABASE_ANON_KEY || '').trim();

const missing = [];
if (!url) missing.push('SUPABASE_URL');
if (!key) missing.push('SUPABASE_ANON_KEY');
if (missing.length) {
  console.error(`Missing environment variable(s): ${missing.join(', ')}. Set them in Netlify -> Site configuration -> Environment variables.`);
  process.exit(1);
}
if (!/^https?:\/\/[^\s'"]+$/.test(url)) {
  console.error('SUPABASE_URL does not look like a URL.');
  process.exit(1);
}
if (/[\s'"\\]/.test(key)) {
  console.error('SUPABASE_ANON_KEY contains spaces, quotes or backslashes.');
  process.exit(1);
}

const out = fileURLToPath(new URL('../web/config.js', import.meta.url));
writeFileSync(out, `// Generated by scripts/write-config.mjs during the hosted build. Do not edit here.
export const SUPABASE_URL = '${url}';
export const SUPABASE_ANON_KEY = '${key}';
`);
console.log(`Wrote web/config.js for ${url}`);
